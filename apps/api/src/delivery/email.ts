import { z } from "zod"

export const emailLimits = Object.freeze({
  maximumAttachments: 6,
  attachmentDecodedBytes: 2 * 1024 * 1024,
  totalAttachmentBase64Bytes: 12 * 1024 * 1024,
  textUtf8Bytes: 64 * 1024,
  requestJsonBytes: 13 * 1024 * 1024,
  automaticSendWindowMs: 23 * 60 * 60_000,
  timeoutMs: 10_000,
})
const utf8 = new TextEncoder()
function forbiddenControls(value: string, body = false): boolean {
  for (const character of value) {
    const code = character.charCodeAt(0)
    if (body && [9, 10, 13].includes(code)) continue
    if (
      code < 32 ||
      (code >= 127 && code <= 159) ||
      (!body && (code === 0x2028 || code === 0x2029))
    )
      return true
  }
  return false
}
const bareEmail = z
  .email()
  .max(254)
  .refine((value) => !forbiddenControls(value))
function senderMailbox(value: string): string | null {
  if (bareEmail.safeParse(value).success) return value
  const match = /^([^<>"\\,;]{1,100}) <([^<>]+)>$/u.exec(value)
  if (!match || forbiddenControls(value) || match[1] !== match[1]!.trim())
    return null
  return bareEmail.safeParse(match[2]).success ? match[2]! : null
}
const senderSchema = z
  .string()
  .min(3)
  .max(358)
  .refine((value) => senderMailbox(value) !== null)
const deliveryIdSchema = z.string().regex(/^[A-Za-z0-9][A-Za-z0-9_-]{0,127}$/)
const providerIdSchema = z.uuid()
const maximumBase64Length =
  Math.ceil(emailLimits.attachmentDecodedBytes / 3) * 4
function pdfBase64(value: string): boolean {
  if (
    !value.length ||
    value.length > maximumBase64Length ||
    value.length % 4 !== 0
  )
    return false
  // A linear scan avoids recursive regex backtracking on megabyte attachment strings.
  const alphabet =
    "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
  const padding = value.endsWith("==") ? 2 : value.endsWith("=") ? 1 : 0
  for (let index = 0; index < value.length - padding; index++)
    if (!alphabet.includes(value[index]!)) return false
  if (value.slice(value.length - padding) !== "=".repeat(padding)) return false
  const last = alphabet.indexOf(value[value.length - padding - 1]!)
  if (
    (padding === 2 && (last & 15) !== 0) ||
    (padding === 1 && (last & 3) !== 0)
  )
    return false
  if ((value.length / 4) * 3 - padding > emailLimits.attachmentDecodedBytes)
    return false
  // The payload is generated by the ticket PDF service; this transport validates its media signature.
  try {
    return atob(value.slice(0, 12)).startsWith("%PDF-")
  } catch {
    return false
  }
}
export const emailPdfAttachmentSchema = z
  .strictObject({
    filename: z
      .string()
      .min(5)
      .max(120)
      .regex(/^[A-Za-z0-9][A-Za-z0-9_.-]*\.pdf$/)
      .refine((name) => !name.includes("..")),
    content: z.string().max(maximumBase64Length).refine(pdfBase64),
  })
  .readonly()
export const emailRequestSchema = z
  .strictObject({
    deliveryId: deliveryIdSchema,
    idempotencyKey: z.string().min(1).max(256),
    from: senderSchema,
    to: bareEmail,
    subject: z
      .string()
      .min(1)
      .max(200)
      .refine((value) => !forbiddenControls(value)),
    text: z
      .string()
      .min(1)
      .max(emailLimits.textUtf8Bytes)
      .refine(
        (value) =>
          utf8.encode(value).length <= emailLimits.textUtf8Bytes &&
          !forbiddenControls(value, true)
      ),
    attachments: z
      .array(emailPdfAttachmentSchema)
      .max(emailLimits.maximumAttachments)
      .readonly()
      .optional(),
  })
  .superRefine((request, context) => {
    if (request.idempotencyKey !== `elc-email/${request.deliveryId}`)
      context.addIssue({
        code: "custom",
        path: ["idempotencyKey"],
        message: "The key must be derived from the immutable delivery ID.",
      })
    if (
      (request.attachments ?? []).reduce(
        (size, item) => size + item.content.length,
        0
      ) > emailLimits.totalAttachmentBase64Bytes
    )
      context.addIssue({
        code: "custom",
        path: ["attachments"],
        message: "The encoded attachment total exceeds the local limit.",
      })
    if (
      new Set((request.attachments ?? []).map((item) => item.filename)).size !==
      (request.attachments?.length ?? 0)
    )
      context.addIssue({
        code: "custom",
        path: ["attachments"],
        message: "Attachment filenames must be unique.",
      })
  })
  .readonly()
export type EmailRequest = z.infer<typeof emailRequestSchema>
export type EmailPdfAttachment = z.infer<typeof emailPdfAttachmentSchema>
export type EmailFailureDisposition =
  | "unavailable"
  | "uncertain"
  | "retryable"
  | "review_needed"
  | "permanent"
export type EmailFailureCode =
  | "UNAVAILABLE"
  | "INVALID_REQUEST"
  | "INVALID_PROVIDER_ID"
  | "SEND_WINDOW_EXPIRED"
  | "SEND_LEASE_EXPIRED"
  | "CLOCK_UNSAFE"
  | "NETWORK_UNCERTAIN"
  | "TIMEOUT"
  | "PROVIDER_UNCERTAIN"
  | "INVALID_PROVIDER_RESPONSE"
  | "RATE_LIMITED"
  | "IDEMPOTENCY_BUSY"
  | "IDEMPOTENCY_MISMATCH"
  | "PROVIDER_REJECTED"
  | "PROVIDER_BINDING_MISMATCH"
/** Only application-owned codes may leave this boundary; never attach a provider error as cause. */
export class EmailTransportError extends Error {
  readonly code: EmailFailureCode
  readonly disposition: EmailFailureDisposition
  readonly httpStatus: number | null
  constructor(
    code: EmailFailureCode,
    disposition: EmailFailureDisposition,
    httpStatus: number | null = null
  ) {
    super(`Email transport failed: ${code}`)
    this.name = "EmailTransportError"
    this.code = code
    this.disposition = disposition
    this.httpStatus = httpStatus
  }
}
export function freezeEmailRequest(raw: unknown): EmailRequest {
  const parsed = emailRequestSchema.safeParse(raw)
  if (!parsed.success)
    throw new EmailTransportError("INVALID_REQUEST", "permanent")
  return parsed.data
}
const providerStatuses = [
  "bounced",
  "canceled",
  "clicked",
  "complained",
  "delivered",
  "delivery_delayed",
  "failed",
  "opened",
  "queued",
  "scheduled",
  "sent",
  "suppressed",
] as const
export type EmailProviderStatus = (typeof providerStatuses)[number]
export type EmailSendResult = Readonly<{
  provider: "resend"
  deliveryId: string
  providerEmailId: string
  status: "accepted"
}>
export type EmailLookupResult = Readonly<{
  provider: "resend"
  deliveryId: string
  providerEmailId: string
  status: EmailProviderStatus
}>
export type EmailAttemptContext = Readonly<{
  firstAttemptAt: number
  lastAttemptAt?: number
  leaseExpiresAt?: number
}>
export interface EmailAdapter {
  send(
    request: EmailRequest,
    context: EmailAttemptContext
  ): Promise<EmailSendResult>
  lookup(
    providerEmailId: string,
    request: EmailRequest
  ): Promise<EmailLookupResult>
}
type Dependencies = { fetch?: typeof fetch; now?: () => number }
const sendResponse = z.object({ id: providerIdSchema })
const lookupResponse = z.object({
  id: providerIdSchema,
  from: senderSchema,
  to: z.array(bareEmail).length(1),
  last_event: z.enum(providerStatuses),
})

function payload(request: EmailRequest): string {
  const body = JSON.stringify({
    from: request.from,
    to: [request.to],
    subject: request.subject,
    text: request.text,
    ...(request.attachments === undefined
      ? {}
      : {
          attachments: request.attachments.map((attachment) => ({
            filename: attachment.filename,
            content: attachment.content,
          })),
        }),
  })
  if (utf8.encode(body).length > emailLimits.requestJsonBytes)
    throw new EmailTransportError("INVALID_REQUEST", "permanent")
  return body
}
async function boundedJson(
  response: Response,
  maximumBytes: number,
  signal: AbortSignal
): Promise<unknown> {
  if (!response.body) throw new Error("missing response")
  const reader = response.body.getReader()
  const abort = () => {
    void reader.cancel().catch(() => {})
  }
  signal.addEventListener("abort", abort, { once: true })
  if (signal.aborted) abort()
  const chunks: Uint8Array[] = []
  let size = 0
  try {
    while (true) {
      const chunk = await reader.read()
      if (chunk.done) break
      size += chunk.value.byteLength
      if (size > maximumBytes) throw new Error("response limit")
      chunks.push(chunk.value)
    }
    const bytes = new Uint8Array(size)
    let offset = 0
    for (const chunk of chunks) {
      bytes.set(chunk, offset)
      offset += chunk.byteLength
    }
    return JSON.parse(
      new TextDecoder("utf-8", { fatal: true }).decode(bytes)
    ) as unknown
  } finally {
    signal.removeEventListener("abort", abort)
    void reader.cancel().catch(() => {})
    reader.releaseLock()
  }
}
function sameMailbox(left: string, right: string): boolean {
  // Domains are case-insensitive; preserve local-part identity instead of guessing provider aliases.
  const split = (value: string) => {
    const at = value.lastIndexOf("@")
    return [value.slice(0, at), value.slice(at + 1).toLowerCase()]
  }
  const [leftName, leftDomain] = split(left)
  const [rightName, rightDomain] = split(right)
  return leftName === rightName && leftDomain === rightDomain
}

export function createResendEmailAdapter(
  configuration: { apiKey?: string },
  dependencies: Dependencies = {}
): EmailAdapter {
  const fetcher = dependencies.fetch ?? fetch
  const now = dependencies.now ?? Date.now
  const apiKey = configuration.apiKey
  let latestSendClock: number | null = null
  const available = () => {
    if (!apiKey || !/^[A-Za-z0-9_-]{1,256}$/.test(apiKey))
      throw new EmailTransportError("UNAVAILABLE", "unavailable")
  }
  const request = async (
    path: string,
    method: "POST" | "GET",
    body?: string,
    idempotencyKey?: string
  ): Promise<unknown> => {
    const controller = new AbortController()
    let timeout!: ReturnType<typeof setTimeout>
    const expired = new Promise<never>((_, reject) => {
      timeout = setTimeout(() => {
        controller.abort()
        reject(new EmailTransportError("TIMEOUT", "uncertain"))
      }, emailLimits.timeoutMs)
    })
    const work = async () => {
      let response: Response
      try {
        response = await fetcher(`https://api.resend.com${path}`, {
          method,
          headers: {
            Authorization: `Bearer ${apiKey}`,
            "Content-Type": "application/json",
            ...(idempotencyKey ? { "Idempotency-Key": idempotencyKey } : {}),
          },
          ...(body === undefined ? {} : { body }),
          redirect: "manual",
          signal: controller.signal,
        })
      } catch {
        throw new EmailTransportError("NETWORK_UNCERTAIN", "uncertain")
      }
      if (!response.ok) {
        const status = response.status
        if (status === 409) {
          let name: string | null = null
          try {
            const parsed = z
              .object({ name: z.string().max(100) })
              .safeParse(await boundedJson(response, 4096, controller.signal))
            if (parsed.success) name = parsed.data.name
          } catch {
            /* Only two explicit machine codes affect conflict handling. */
          }
          if (name === "invalid_idempotent_request")
            throw new EmailTransportError(
              "IDEMPOTENCY_MISMATCH",
              "review_needed",
              status
            )
          if (name === "concurrent_idempotent_requests")
            throw new EmailTransportError(
              "IDEMPOTENCY_BUSY",
              "retryable",
              status
            )
        } else void response.body?.cancel().catch(() => {})
        if (status === 429)
          throw new EmailTransportError("RATE_LIMITED", "retryable", status)
        if (status >= 500 || status === 408 || status < 400)
          throw new EmailTransportError(
            "PROVIDER_UNCERTAIN",
            "uncertain",
            status
          )
        throw new EmailTransportError("PROVIDER_REJECTED", "permanent", status)
      }
      try {
        return await boundedJson(
          response,
          method === "POST" ? 4096 : 256 * 1024,
          controller.signal
        )
      } catch {
        throw new EmailTransportError(
          "INVALID_PROVIDER_RESPONSE",
          "uncertain",
          response.status
        )
      }
    }
    try {
      return await Promise.race([work(), expired])
    } finally {
      clearTimeout(timeout)
    }
  }
  return {
    async send(raw, context) {
      available()
      const frozen = freezeEmailRequest(raw)
      const body = payload(frozen)
      const current = now()
      if (
        !context ||
        !Number.isSafeInteger(context.firstAttemptAt) ||
        context.firstAttemptAt < 0 ||
        !Number.isSafeInteger(current) ||
        current < context.firstAttemptAt ||
        (latestSendClock !== null && current < latestSendClock) ||
        (context.lastAttemptAt !== undefined &&
          (!Number.isSafeInteger(context.lastAttemptAt) ||
            context.lastAttemptAt < context.firstAttemptAt ||
            current < context.lastAttemptAt))
      )
        throw new EmailTransportError("CLOCK_UNSAFE", "review_needed")
      latestSendClock = current
      if (
        context.leaseExpiresAt !== undefined &&
        (!Number.isSafeInteger(context.leaseExpiresAt) ||
          current >= context.leaseExpiresAt)
      )
        throw new EmailTransportError("SEND_LEASE_EXPIRED", "retryable")
      if (current - context.firstAttemptAt >= emailLimits.automaticSendWindowMs)
        throw new EmailTransportError("SEND_WINDOW_EXPIRED", "review_needed")
      const parsed = sendResponse.safeParse(
        await request("/emails", "POST", body, frozen.idempotencyKey)
      )
      if (!parsed.success)
        throw new EmailTransportError("INVALID_PROVIDER_RESPONSE", "uncertain")
      return Object.freeze({
        provider: "resend",
        deliveryId: frozen.deliveryId,
        providerEmailId: parsed.data.id,
        status: "accepted",
      })
    },
    async lookup(rawId, raw) {
      available()
      const frozen = freezeEmailRequest(raw)
      const id = providerIdSchema.safeParse(rawId)
      if (!id.success)
        throw new EmailTransportError("INVALID_PROVIDER_ID", "permanent")
      const parsed = lookupResponse.safeParse(
        await request(`/emails/${id.data}`, "GET")
      )
      if (!parsed.success)
        throw new EmailTransportError("INVALID_PROVIDER_RESPONSE", "uncertain")
      const value = parsed.data
      if (
        value.id !== id.data ||
        !sameMailbox(value.to[0]!, frozen.to) ||
        !sameMailbox(senderMailbox(value.from)!, senderMailbox(frozen.from)!)
      )
        throw new EmailTransportError(
          "PROVIDER_BINDING_MISMATCH",
          "review_needed"
        )
      return Object.freeze({
        provider: "resend",
        deliveryId: frozen.deliveryId,
        providerEmailId: value.id,
        status: value.last_event,
      })
    },
  }
}
