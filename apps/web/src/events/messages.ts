export type EventMessageKey = keyof typeof text
export function eventText(locale: Locale, key: EventMessageKey): string {
  return text[key][locale === "kk" ? 0 : locale === "ru" ? 1 : 2]
}
export function useEventText() {
  const { locale } = useAccount()
  return { locale, t: (key: EventMessageKey) => eventText(locale, key) }
}
